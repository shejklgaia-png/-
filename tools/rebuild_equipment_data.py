#!/usr/bin/env python3
"""Embed normalized A/B equipment for exported SERA builds.

Run after editing models/core/Equipment.bbmodel:
    python3 tools/rebuild_equipment_data.py

Godot Android editor prefers the live .bbmodel when accessible; the generated
GDScript remains the export fallback when loose .bbmodel files are absent.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "models" / "core" / "Equipment.bbmodel"
OUTPUT = ROOT / "assets" / "sera_equipment_data.gd"


def main() -> None:
    model = json.loads(MODEL.read_text(encoding="utf-8"))
    # The base A rig uses assets/sera_source.json; only modeling geometry and
    # hierarchy are needed here. Animation tracks must not be duplicated.
    payload = {
        "groups": model.get("groups", []),
        "elements": model.get("elements", []),
        "outliner": model.get("outliner", []),
    }
    compact = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    chunks = [compact[i:i + 120] for i in range(0, len(compact), 120)]
    body = "\n".join("    " + json.dumps(chunk, ensure_ascii=False) + "," for chunk in chunks)
    OUTPUT.write_text(
        "## Generated by tools/rebuild_equipment_data.py; do not edit by hand.\n"
        "const PARTS = [\n" + body + "\n]\n"
        "static func get_json() -> String:\n"
        "    return \"\".join(PackedStringArray(PARTS))\n",
        encoding="utf-8",
    )
    print(f"Embedded {len(model.get('elements', []))} Blockbench meshes ({len(compact)} characters)")


if __name__ == "__main__":
    main()
