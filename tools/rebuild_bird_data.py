#!/usr/bin/env python3
"""Generate the bird-leg runtime snapshot from the canonical BirdLeg Blockbench file."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "models/core/BirdLeg.bbmodel"
OUTPUT = ROOT / "assets/sera_bird_data.gd"

def build(data):
    groups = {g["uuid"]: g for g in data["groups"]}
    meshes = {e["uuid"]: e for e in data["elements"]}
    bird = {uid for uid, g in groups.items() if
            g["name"] in {f"Bird_{part}_{side}" for part in ("Thigh", "LowerLeg", "Foot") for side in "LR"}}
    assert len(bird) == 6
    waist = next(e for e in data["outliner"] if isinstance(e, dict)
                 and groups[e["uuid"]]["name"] == "Waist")
    selected = [e for e in waist["children"] if
                (isinstance(e, str) and meshes[e]["name"].startswith("Bird_Waist_Armor"))
                or (isinstance(e, dict) and groups[e["uuid"]]["name"] in ("Bird_Thigh_L", "Bird_Thigh_R"))]
    assert len(selected) == 4
    found = set()
    def walk(entry):
        if isinstance(entry, str):
            found.add(entry)
        else:
            for c in entry["children"]:
                walk(c)
    for entry in selected:
        walk(entry)
    assert len(found) == 10
    return {
        "groups": [g for g in data["groups"] if g["uuid"] in bird],
        "elements": [e for e in data["elements"] if e["uuid"] in found],
        "outliner": selected,
        "animations": [
            {"name": a["name"], "length": a["length"], "loop": a.get("loop"),
             "animators": {uid: track for uid, track in a.get("animators", {}).items() if uid in bird}}
            for a in data["animations"]
        ],
    }

def main():
    slim = build(json.loads(MODEL.read_text(encoding="utf-8")))
    s = json.dumps(slim, ensure_ascii=False, separators=(",", ":"))
    chunks = [s[i:i+120] for i in range(0, len(s), 120)]
    out = ("extends RefCounted\n## Generated by tools/rebuild_bird_data.py; bird bones/meshes/tracks only.\n"
           "const PARTS = [\n" +
           "\n".join("    " + json.dumps(x, ensure_ascii=False) + "," for x in chunks) +
           "\n]\nstatic func get_json() -> String:\n    return \"\".join(PackedStringArray(PARTS))\n")
    OUTPUT.write_text(out, encoding="utf-8")
    print(f"Embedded {len(slim['groups'])} bird bones, {len(slim['elements'])} meshes, {len(slim['animations'])} clips")

if __name__ == "__main__":
    main()
