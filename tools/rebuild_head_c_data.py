#!/usr/bin/env python3
"""Generate export-safe standalone Head C geometry from its single model source."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models/storage/Head_C.bbmodel"
OUTPUT = ROOT / "assets/sera_head_c_data.gd"

def generate() -> str:
    model = json.loads(SOURCE.read_text(encoding="utf-8"))
    payload = {key: model[key] for key in ("groups", "elements", "outliner")}
    assert len(payload["elements"]) == 2 and len(payload["outliner"]) == 1
    # The original export was serialized by JSON.stringify, which writes
    # integral float values (e.g. 1.0) as 1. Preserve exactly that canonical
    # byte representation while retaining the same numeric pivot coordinates.
    def normalize_number(value):
        if type(value) is float and value.is_integer():
            return int(value)
        if isinstance(value, list):
            return [normalize_number(part) for part in value]
        if isinstance(value, dict):
            return {key: normalize_number(part) for key, part in value.items()}
        return value
    compact = json.dumps(normalize_number(payload), ensure_ascii=False, separators=(",", ":"))
    chunks = [compact[i:i + 120] for i in range(0, len(compact), 120)]
    lines = "\n".join("    " + json.dumps(part, ensure_ascii=False) + "," for part in chunks)
    return ("## Generated by tools/rebuild_head_c_data.py; do not edit by hand.\n"
            "const PARTS = [\n" + lines + "\n]\n"
            "static func get_json() -> String:\n"
            '    return "".join(PackedStringArray(PARTS))\n')

if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8")
    print("Embedded Head C: two meshes")
