#!/usr/bin/env python3
"""Generate an export-safe GDScript snapshot of the standard-skeleton D lower body."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models/storage/LowerBody_D.bbmodel"
OUTPUT = ROOT / "assets/sera_lower_body_d_data.gd"


def generate() -> str:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    payload = {key: source[key] for key in ("groups", "elements", "outliner")}
    assert len(payload["groups"]) == 7 and len(payload["elements"]) == 12
    compact = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    chunks = [compact[i:i + 120] for i in range(0, len(compact), 120)]
    lines = "\n".join("    " + json.dumps(chunk, ensure_ascii=False) + "," for chunk in chunks)
    return (
        "## Generated by tools/rebuild_lower_body_d_data.py; do not edit by hand.\n"
        "const PARTS = [\n" + lines + "\n]\n"
        "static func get_json() -> String:\n"
        '    return "".join(PackedStringArray(PARTS))\n'
    )


if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8")
    print("Embedded standard lower-body D: seven joints, twelve meshes")
