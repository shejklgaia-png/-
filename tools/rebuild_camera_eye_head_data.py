#!/usr/bin/env python3
"""Embed the exact authored camera-eye Blockbench model for Android exports."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models" / "storage" / "カメラアイ頭部.bbmodel"
OUTPUT = ROOT / "assets" / "sera_camera_eye_head_data.gd"


def generate() -> str:
    # Preserve the author's complete model and embedded 16x16 PNG, including
    # exact vertex coordinates, UV layout, face winding and source pivots.
    authored = SOURCE.read_text(encoding="utf-8")
    data = json.loads(authored)
    if data.get("name") != "カメラアイ頭部" or not data.get("elements") or not data.get("textures"):
        raise ValueError("Camera-eye Blockbench source is incomplete")
    if not data["textures"][0].get("source", "").startswith("data:image/png;base64,"):
        raise ValueError("Camera-eye color texture is missing from the model")
    chunks = [authored[i:i + 120] for i in range(0, len(authored), 120)]
    lines = "\n".join("    " + json.dumps(part, ensure_ascii=False) + ","
                      for part in chunks)
    return (
        "## Generated by tools/rebuild_camera_eye_head_data.py; do not edit by hand.\n"
        "const PARTS = [\n" + lines + "\n]\n"
        "static func get_json() -> String:\n"
        '    return "".join(PackedStringArray(PARTS))\n'
    )


if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8")
    print("Embedded camera-eye head source and author texture for HEAD D")
