#!/usr/bin/env python3
"""Embed the two real authored Katana clips for Android export fallback."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "models/core/Katana.bbmodel"
OUTPUT = ROOT / "assets/sera_katana_data.gd"


def build() -> str:
    authored = json.loads(SOURCE.read_text(encoding="utf-8"))
    clips = [c for c in authored["animations"] if c["name"] in ("Melee_katana", "Melee_katana2")]
    assert len(clips) == 2 and len({c["name"] for c in clips}) == 2
    compact = json.dumps({"animations": clips}, ensure_ascii=False, separators=(",", ":"))
    chunks = [compact[i:i+120] for i in range(0, len(compact), 120)]
    return (
        "extends RefCounted\n## Generated by tools/rebuild_katana_data.py; two authored Katana clips only.\n"
        "const PARTS = [\n" +
        "\n".join("    " + json.dumps(x, ensure_ascii=False) + "," for x in chunks) +
        "\n]\nstatic func get_json() -> String:\n"
        '    return "".join(PackedStringArray(PARTS))\n'
    )


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8")
    print("Embedded original Katana1/Katana2 clips for export")
